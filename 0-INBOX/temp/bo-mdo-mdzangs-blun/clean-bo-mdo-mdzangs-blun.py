#!/usr/bin/env python3
"""
clean-bo-mdo-mdzangs-blun.py
Generated by the clean-raw-text skill.
Cleans mechanical debris from:
  1-SOURCES/Text/མཛངས་བླུན་ཞེས་བྱ་བའི་མདོ་ཡི་ཡིག་རྐྱང་ཆ་ཚང་།.txt
Output:
  0-INBOX/temp/bo-mdo-mdzangs-blun/cleaned.md
Run from the repo root.  Profile found: BOM, whole text on ONE line (no paragraph
breaks); no page markers, headers/footers, U+0F0C, mid-word spaces or digits.
Nothing in the text itself is edited.
"""
import re
from pathlib import Path

SOURCE = Path("1-SOURCES/Text/མཛངས་བླུན་ཞེས་བྱ་བའི་མདོ་ཡི་ཡིག་རྐྱང་ཆ་ཚང་།.txt")
OUTPUT = Path("0-INBOX/temp/bo-mdo-mdzangs-blun/cleaned.md")

NBT, STD_TSHEG = '༌', '་'
# Section-closing mark: double shad + space + double shad (colophons: "...ལེའུ་སྟེ་དང་པོའོ།། །།")
SECTION_END = re.compile(r'(།། །།)[ ]*')

def clean(text):
    stats = {}
    # 1. BOM
    stats['bom'] = text.startswith('﻿'); text = text.lstrip('﻿')
    # 2. line endings / non-breaking tsheg / nbsp
    text = text.replace('\r\n', '\n').replace('\r', '\n')
    stats['nbt'] = text.count(NBT); text = text.replace(NBT, STD_TSHEG)
    text = text.replace('\xa0', ' ')
    # 3. paragraph breaks: the source is a single line; end a paragraph after each
    #    section-closing "།། །།" (chapter / volume / colophon marks). No text changed.
    n = len(SECTION_END.findall(text))
    text = SECTION_END.sub(r'\1\n\n', text)
    stats['paragraph_breaks'] = n
    # 4. trailing whitespace per line, collapse blank-line runs
    text = '\n'.join(l.rstrip() for l in text.split('\n'))
    text = re.sub(r'\n{3,}', '\n\n', text).strip() + '\n'
    return text, stats

if __name__ == '__main__':
    src = SOURCE.read_text(encoding='utf-8')
    out, st = clean(src)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(out, encoding='utf-8')
    # integrity check: removing all whitespace must leave identical text
    strip = lambda s: re.sub(r'\s+', '', s.lstrip('﻿'))
    assert strip(src) == strip(out), 'content changed!'
    print(f"Done — {st}; paragraphs: {out.count(chr(10)+chr(10))+1}; chars {len(src)} -> {len(out)}")
    print("Integrity check passed (text identical apart from whitespace/BOM).")
    print(f"Written to: {OUTPUT}")
